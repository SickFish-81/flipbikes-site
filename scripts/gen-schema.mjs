/* Generates the Product structured data (JSON-LD) that sits in the <head> of
 * public/index.html, and writes it between the BEGIN/END markers there.
 *
 *   node scripts/gen-schema.mjs        # rewrite index.html
 *   node scripts/gen-schema.mjs --check  # exit 1 if index.html is out of date
 *
 * WHY A GENERATOR AND NOT JUST TYPED-IN JSON
 * ------------------------------------------
 * Structured data is a price quoted to Google, and Google shows it in the
 * search result. If it drifts from catalog.js the search listing advertises
 * one number while Stripe charges another - the same Fair Trading problem the
 * page's own prices had until last commit, except this copy is invisible, so
 * nobody would ever notice it had gone stale.
 *
 * The visible prices solve this at runtime (shop.js reads /api/shop). JSON-LD
 * cannot: crawlers other than Google mostly do not run JavaScript, so the
 * markup has to be in the file as served. So instead the file is GENERATED
 * from catalog.js and test/shop.test.js runs this in --check mode. Change a
 * price in catalog.js and forget to regenerate, and the test fails and tells
 * you the command to run. The price still lives in exactly one place.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { PRODUCTS } from "../api/_lib/catalog.js";

const SITE = "https://www.flipbikes.co.nz";
const PAGE = new URL("../public/index.html", import.meta.url);
const BEGIN = "  <!-- BEGIN product schema: generated by scripts/gen-schema.mjs - do not edit by hand -->";
const END = "  <!-- END product schema -->";

/* What catalog.js does not know: the picture and the sales copy. Money and
 * names stay in catalog.js; this is only presentation. Every SKU must appear
 * here or the script throws - a new product cannot slip into the shop with no
 * structured data. */
const EXTRA = {
  "flip-starter-pack": {
    image: "images/Starter-Pack-1.png",
    description: "One Standard FLIP bike chock, two recessed D rings and two tie-downs - everything needed to fit out a trailer for one bike.",
  },
  "flip-g3": {
    image: "images/Gen-3-1.png",
    description: "The G3 recessed motorcycle wheel chock, flanged the whole way around. Folds flat into the trailer floor when not in use.",
  },
  "flip-standard": {
    image: "images/Original-2.png",
    description: "The original FLIP recessed motorcycle wheel chock. Fits kids' bikes through to big trail bikes, and folds flat into the trailer floor.",
  },
  "flip-road": {
    image: "images/Gen-3-1.png",
    description: "A wider FLIP chock made for the low-profile rims on road bikes, which do not fit the Standard chock.",
  },
  "tie-downs": {
    image: "images/Tie-Downs.png",
    description: "Tie-downs for pulling the bike forward and down onto the FLIP mount.",
  },
  "d-rings": {
    image: "images/D-Rings.png",
    description: "Heavy-duty recessed D rings for anchoring tie-downs to the trailer floor.",
  },
};

// Cents to the decimal string schema.org wants: 17900 -> "179.00".
const dollars = (cents) => (cents / 100).toFixed(2);

export function schema() {
  const brand = { "@type": "Brand", name: "FLIP" };
  const products = PRODUCTS.map((p) => {
    const extra = EXTRA[p.sku];
    if (!extra) {
      throw new Error(
        `No image/description for "${p.sku}" in scripts/gen-schema.mjs. Add one, ` +
        `then re-run: node scripts/gen-schema.mjs`,
      );
    }
    return {
      "@type": "Product",
      name: p.name,
      sku: p.sku,
      description: extra.description,
      image: `${SITE}/${extra.image}`,
      brand,
      offers: {
        "@type": "Offer",
        url: `${SITE}/`,
        priceCurrency: "NZD",
        price: dollars(p.price),           // <- from catalog.js, never typed here
        // GST-inclusive, like every price on the site. Saying so stops Google
        // reading it as ex-GST and showing a number 15% under what we charge.
        priceSpecification: {
          "@type": "PriceSpecification",
          price: dollars(p.price),
          priceCurrency: "NZD",
          valueAddedTaxIncluded: true,
        },
        availability: "https://schema.org/InStock",
        itemCondition: "https://schema.org/NewCondition",
        seller: { "@type": "Organization", name: "FLIP Bike Chocks" },
        // Deliberately no shippingDetails. Freight is priced per order from
        // the destination (North Island / South Island / rural / Australia -
        // see shipping.js), so there is no single figure to publish here, and
        // a half-filled shippingDetails block earns a Search Console warning
        // rather than a shipping line in the result. The cart quotes the real
        // number before anyone pays.
      },
    };
  });

  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Organization",
        "@id": `${SITE}/#organization`,
        name: "FLIP Bike Chocks",
        url: `${SITE}/`,
        logo: `${SITE}/images/webclip.png`,
        email: "sales@flipbikes.co.nz",
        telephone: "+64 21 0832 7787",
        address: {
          "@type": "PostalAddress",
          addressLocality: "Tauranga",
          addressCountry: "NZ",
        },
      },
      {
        "@type": "WebSite",
        "@id": `${SITE}/#website`,
        url: `${SITE}/`,
        name: "FLIP Bike Chocks",
        publisher: { "@id": `${SITE}/#organization` },
        inLanguage: "en-NZ",
      },
      {
        "@type": "ItemList",
        name: "FLIP bike chocks and accessories",
        itemListElement: products.map((product, i) => ({
          "@type": "ListItem",
          position: i + 1,
          item: product,
        })),
      },
    ],
  };
}

// The exact text that belongs in index.html, markers included.
export function block() {
  const json = JSON.stringify(schema(), null, 2)
    .split("\n")
    .map((line) => "    " + line)
    .join("\n");
  return `${BEGIN}\n  <script type="application/ld+json">\n${json}\n  </script>\n${END}`;
}

export function render(html) {
  const b = html.indexOf(BEGIN);
  const e = html.indexOf(END);
  if (b === -1 || e === -1) {
    throw new Error("Marker comments missing from public/index.html - cannot place the schema.");
  }
  return html.slice(0, b) + block() + html.slice(e + END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const html = readFileSync(PAGE, "utf8");
  const next = render(html);
  if (process.argv.includes("--check")) {
    if (next !== html) {
      console.error("public/index.html structured data is out of date. Run: node scripts/gen-schema.mjs");
      process.exit(1);
    }
    console.log("structured data is up to date");
  } else if (next === html) {
    console.log("structured data already up to date");
  } else {
    writeFileSync(PAGE, next);
    console.log("public/index.html structured data regenerated");
  }
}
